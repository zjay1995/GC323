/* =====================================================================
   Everything that follows from the model configuration.

   The switches themselves are NOT here any more. They live in one file
   per product under config\ (config\gc323.h, config\gc301.h, ...) and
   tools\build.bat copies the one you asked for to src\MODELCFG.H before
   compiling. Editing switches by hand before a build is what this split
   exists to stop.

   To change a setting: edit config\<model>.h and commit it.
   To build:            tools\build.bat <model>
   ===================================================================== */

